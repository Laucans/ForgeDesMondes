//! `checked` and `Upload::prepare`: the media library's payload made the
//! command written on `Media/<a new id>` — or refused before it is queued.

use serde_json::{Value, json};
use upload_media::{Fresh, Place, Prepared, Refusal, Row, checked, default_grid, names};

const VALOMBRE: &str = "c1000000-0000-4000-8000-000000000001";
const BRUME: &str = "c1000000-0000-4000-8000-000000000002";
const TAVERNE: &str = "e1000000-0000-4000-8000-000000000002";
const CARTE: &str = "a1000000-0000-4000-8000-000000000001";
const NOW: &str = "2026-10-20T10:00:00.000Z";

fn row(value: Value) -> Row {
    let Value::Object(map) = value else {
        panic!("a row is an object");
    };
    map.into_iter().collect()
}

fn fresh() -> Fresh<'static> {
    Fresh {
        media: CARTE,
        now: NOW,
    }
}

fn lieu(campaign: &str) -> Place {
    Place {
        kind: "lieu".to_owned(),
        campaign: campaign.to_owned(),
    }
}

/// `wire` uploaded, its place — when it names one — read as `place`.
fn upload(wire: Value, place: Option<&Place>) -> Result<Prepared, Refusal> {
    checked(&row(wire))?.prepare(place, fresh())
}

/// The place `wire` names, once checked.
fn place_named(wire: &Value) -> Option<String> {
    checked(&row(wire.clone()))
        .expect("checked")
        .place()
        .map(str::to_owned)
}

/// The campaign `wire` names, once checked.
fn campaign_named(wire: &Value) -> String {
    checked(&row(wire.clone()))
        .expect("checked")
        .campaign()
        .to_owned()
}

fn uploaded(wire: Value) -> Row {
    upload(wire, None).expect("prepared").payload
}

fn battlemap() -> Value {
    json!({
        "campaign": VALOMBRE,
        "kind": "battlemap",
        "title": "  La Taverne du Sanglier ",
        "file": "/Users/dm/cartes/taverne.png",
        "width": 2048,
        "height": 1536,
    })
}

fn with(mut base: Value, field: &str, value: Value) -> Value {
    base[field] = value;
    base
}

#[test]
fn the_id_is_named_with_or_without_its_version() {
    assert!(names("media.uploadMedia"));
    assert!(names("media.uploadMedia@1"));
    assert!(!names("media.saveGridSettings@1"));
}

#[test]
fn a_battlemap_is_written_on_its_new_partition_with_the_default_grid() {
    let prepared = upload(battlemap(), None).expect("prepared");
    assert_eq!(prepared.target_id, CARTE);
    let mut expected = row(json!({
        "id": CARTE,
        "campaignId": VALOMBRE,
        "kind": "battlemap",
        "title": "La Taverne du Sanglier",
        "filePath": "/Users/dm/cartes/taverne.png",
        "widthPx": 2048,
        "heightPx": 1536,
        "placeId": null,
        "uploadedAt": NOW,
        "mediaId": CARTE,
    }));
    expected.extend(default_grid());
    assert_eq!(prepared.payload, expected);
}

#[test]
fn the_default_grid_is_the_mock_up_s_new_battlemap_s_a_valid_one() {
    // grid-values-range: a hex above 0, an opacity from 0 to 1 — the mock-up's
    // 45 % as a fraction; grid-only-for-battlemap: every setting is there.
    assert_eq!(
        default_grid(),
        row(json!({
            "hexSizePx": 32, "offsetX": 0, "offsetY": 0,
            "orientation": "pointe", "color": "text", "opacity": 0.45,
        }))
    );
    // hex-is-five-feet: generated by the table, never written.
    assert!(!uploaded(battlemap()).contains_key("feetPerHex"));
}

#[test]
fn an_illustration_has_no_grid() {
    // grid-only-for-battlemap: none of the grid's fields, nor the battlemap
    // it would set.
    let payload = uploaded(with(battlemap(), "kind", json!("illustration")));
    assert_eq!(payload["kind"], "illustration");
    for field in default_grid().keys().map(String::as_str).chain(["mediaId"]) {
        assert!(!payload.contains_key(field), "{field}");
    }
}

#[test]
fn an_upload_without_a_place_has_none() {
    for place in [Value::Null, json!("")] {
        let wire = with(battlemap(), "place", place);
        assert_eq!(place_named(&wire), None);
        assert_eq!(uploaded(wire)["placeId"], Value::Null);
    }
}

#[test]
fn a_lieu_of_the_same_campaign_is_the_media_s_place_whatever_the_case() {
    let wire = with(battlemap(), "place", json!(TAVERNE));
    assert_eq!(place_named(&wire).as_deref(), Some(TAVERNE));
    let place = lieu(&VALOMBRE.to_uppercase());
    let prepared = upload(wire, Some(&place)).expect("prepared");
    assert_eq!(prepared.payload["placeId"], TAVERNE);
}

#[test]
fn media_place_is_lieu_refuses_a_non_lieu_another_campaign_s_lieu_and_an_unknown_element() {
    let wire = with(battlemap(), "place", json!(TAVERNE));
    let pnj = Place {
        kind: "pnj".to_owned(),
        campaign: VALOMBRE.to_owned(),
    };
    for place in [Some(&pnj), Some(&lieu(BRUME)), None] {
        let refusal = upload(wire.clone(), place).expect_err("refused");
        assert_eq!(refusal, Refusal::PlaceNotLieu, "{place:?}");
        assert!(
            refusal.to_string().starts_with("media-place-is-lieu"),
            "{refusal}"
        );
    }
}

#[test]
fn a_checked_upload_names_its_campaign() {
    assert_eq!(campaign_named(&battlemap()), VALOMBRE);
    assert_eq!(
        campaign_named(&with(battlemap(), "campaign", json!(BRUME))),
        BRUME
    );
}

#[test]
fn the_dimensions_and_the_path_are_optional() {
    let payload =
        uploaded(json!({ "campaign": VALOMBRE, "kind": "illustration", "title": "Elowen" }));
    assert_eq!(payload["widthPx"], 0);
    assert_eq!(payload["heightPx"], 0);
    assert_eq!(payload["filePath"], "");
}

#[test]
fn what_the_tables_could_never_hold_is_refused_before_it_is_queued() {
    let without = |field: &str| {
        let mut wire = battlemap();
        wire.as_object_mut().expect("an object").remove(field);
        wire
    };
    let cases = [
        (without("campaign"), Refusal::NoCampaign),
        (
            with(battlemap(), "campaign", json!("valombre")),
            Refusal::NotAnId("campaign"),
        ),
        (with(battlemap(), "kind", json!("carte")), Refusal::NoKind),
        (without("kind"), Refusal::NoKind),
        (with(battlemap(), "title", json!("   ")), Refusal::NoTitle),
        (without("title"), Refusal::NoTitle),
        (with(battlemap(), "file", json!(42)), Refusal::NotAPath),
        (
            with(battlemap(), "title", json!("La\u{0}Taverne")),
            Refusal::Nul("title"),
        ),
        (
            with(battlemap(), "file", json!("taverne\u{0}.png")),
            Refusal::Nul("file"),
        ),
        (
            with(battlemap(), "width", json!(-1)),
            Refusal::NotAPixelCount("width"),
        ),
        (
            with(battlemap(), "height", json!(2_147_483_648_i64)),
            Refusal::NotAPixelCount("height"),
        ),
        (
            with(battlemap(), "width", json!(12.5)),
            Refusal::NotAPixelCount("width"),
        ),
        // Hex digits and hyphens only, short; 36 characters but not a uuid.
        (
            with(battlemap(), "campaign", json!("abcdef")),
            Refusal::NotAnId("campaign"),
        ),
        (
            with(
                battlemap(),
                "campaign",
                json!("c1000000-0000-4000-8000-00000000000g"),
            ),
            Refusal::NotAnId("campaign"),
        ),
        (
            with(battlemap(), "place", json!("taverne-sanglier")),
            Refusal::NotAnId("place"),
        ),
    ];
    // Checked alone: refused before any place is read.
    for (wire, refusal) in cases {
        assert_eq!(checked(&row(wire.clone())).err(), Some(refusal), "{wire}");
    }
}
