type Shared = Arc<Engine>;

/// What the wire protocol is served with: the engine and its rows, the
/// `llm` port an analysis of notes is generated by, the `speech-to-text`
/// port a dictation is transcribed by, and the reads.
struct Served<L, S> {
    engine: Shared,
    rows: Rows,
    llm: Arc<L>,
    speech: Arc<S>,
    reads: Arc<Reads>,
    exports: Arc<exports::Exports>,
}

impl<L, S> Clone for Served<L, S> {
    fn clone(&self) -> Self {
        Self {
            engine: self.engine.clone(),
            rows: self.rows.clone(),
            llm: self.llm.clone(),
            speech: self.speech.clone(),
            reads: self.reads.clone(),
            exports: self.exports.clone(),
        }
    }
}

impl<L, S> FromRef<Served<L, S>> for Arc<exports::Exports> {
    fn from_ref(served: &Served<L, S>) -> Self {
        served.exports.clone()
    }
}

impl<L, S> FromRef<Served<L, S>> for Arc<Reads> {
    fn from_ref(served: &Served<L, S>) -> Self {
        served.reads.clone()
    }
}

impl<L, S> FromRef<Served<L, S>> for Shared {
    fn from_ref(served: &Served<L, S>) -> Self {
        served.engine.clone()
    }
}

/// Why the engine could not be planted.
#[derive(Debug, thiserror::Error)]
pub enum PlantError {
    /// The database could not be reached.
    #[error("database: {0}")]
    Database(#[from] tokio_postgres::Error),
    /// A manifest the checkout holds does not parse.
    #[error("manifest: {0}")]
    Manifest(#[from] serde_json::Error),
    /// The engine refused its store or its queue.
    #[error("engine: {0}")]
    Engine(#[from] Error),
}

/// The engine over this product's manifests and its database.
///
/// # Errors
///
/// [`PlantError`] when the database cannot be reached, a manifest does not
/// parse, or the engine cannot load its queue.
pub async fn plant(url: &str) -> Result<Engine, PlantError> {
    Ok(planted(url).await?.engine)
}

/// What [`planted`] answers: the engine, and the rows it holds, which the
/// wire protocol prepares a save of an element against.
pub struct Planted {
    /// The engine.
    pub engine: Engine,
    /// Its rows.
    pub rows: Rows,
}

/// [`plant`], with the engine's rows, the units' ports on their fakes
/// ([`fakes`]): this crate's binary and the tests'.
///
/// # Errors
///
/// As [`plant`].
pub async fn planted(url: &str) -> Result<Planted, PlantError> {
    planted_with(url, fakes()).await
}

/// What the units' `Prepare`s need, every port on its fake: the `llm` port
/// a save of the AI settings and a connection test reach.
fn fakes() -> harness_dataguard::plugins::Shared {
    let mut shared = harness_dataguard::plugins::Shared::default();
    shared.insert(Arc::new(ports_llm::SharedLlm::new(
        ports_llm::fake::FakeLlm::new(),
    )));
    shared
}

/// [`planted`], the units reading what `shared` holds: the ports a
/// DataCapability's `Prepare` declares it `needs`.
///
/// # Errors
///
/// As [`plant`]; and the engine refuses units that do not fit together — a
/// need nothing shares (`Error::Misconfigured`).
pub async fn planted_with(
    url: &str,
    shared: harness_dataguard::plugins::Shared,
) -> Result<Planted, PlantError> {
    let aliases = Arc::new(Aliases::default());
    let history = Arc::new(history::History::default());
    let notes = Arc::new(notes::Notes::default());
    let plugins = plugins(&aliases);
    let mut tables = None;
    // The Prepares' read-only SQL over the tables (`Context::rows`): none
    // over memory.
    let mut reads: Option<Arc<dyn harness_dataguard::reads::Rows>> = None;
    let store: Arc<dyn Store> = if url == MEMORY {
        Arc::new(MemoryStore::default())
    } else {
        let (client, connection) = tokio_postgres::connect(url, tokio_postgres::NoTls).await?;
        tokio::spawn(async move {
            if let Err(e) = connection.await {
                eprintln!("postgres: {e}");
            }
        });
        let (reading, connection) = tokio_postgres::connect(url, tokio_postgres::NoTls).await?;
        tokio::spawn(async move {
            if let Err(e) = connection.await {
                eprintln!("postgres: {e}");
            }
        });
        reads = Some(Arc::new(ReadOnly::new(reading)));
        // The aggregates' projections in the apply transaction, each landed
        // with its aggregate's move out of this server.
        let inner = PgStore::open(client)
            .await?
            .with_projections(&plugins)
            .await?;
        let store =
            projection::ProjectingStore::new(inner, aliases.clone()).keeping(history.clone());
        store.repair().await;
        store.elements().await;
        store.versions(None).await;
        store.notes(&notes).await;
        let store = Arc::new(store);
        tables = Some(store.clone());
        store
    };
    // Over memory, the engine's rows are the tables: they keep the terms and
    // the versions.
    let kept = (url == MEMORY).then(|| aliases.clone());
    let versions = (url == MEMORY).then(|| history.clone());
    let store: Arc<dyn Store> = Arc::new(
        versioning::Versioning::new(store, kept)
            .keeping(versions)
            .noting(notes.clone()),
    );
    // A new row's id is a random uuid, as the tables key their rows.
    let mut engine = Engine::new(
        store.clone(),
        Arc::new(MemoryNotifier::default()),
        Arc::new(SystemClock),
    )
    .with_ids(Arc::new(RandomIds));
    if let Some(reads) = reads {
        engine = engine.with_rows(reads);
    }
    let engine = bound(engine, plugins, shared)?;
    engine.load().await?;
    Ok(Planted {
        engine,
        rows: Rows::keeping(store, history)
            .reading(tables)
            .knowing(aliases)
            .noting(notes),
    })
}

/// The Entity aggregate's folder, as the registry names its unit.
const ENTITY: &str = "crates/campaign/aggregates/Entity";

/// Every unit's plugin, as the registry gathers them — but the Entity
/// aggregate's judge reads `aliases`, which this server keeps after its
/// tables ([`projection::ProjectingStore`], [`versioning::Versioning`]),
/// where the aggregate's own plugin would keep the engine's writes: a save
/// the tables refused takes no term.
fn plugins(aliases: &Arc<Aliases>) -> Plugins {
    dataguard_registry::AGGREGATES
        .iter()
        .chain(dataguard_registry::DATA_CAPABILITIES)
        .chain(dataguard_registry::CAPABILITIES)
        .filter_map(|unit| {
            let plugin = unit.plugin?;
            Some(if unit.folder == ENTITY {
                aggregate_entity::judging(aliases.clone())
            } else {
                plugin()
            })
        })
        .collect()
}

/// `engine` bound to what the checkout holds: the registry, every
/// aggregate and DataCapability, every unit's plugin — the aggregates'
/// judges among them — and what `shared` holds for them.
fn bound(
    engine: Engine,
    plugins: Plugins,
    shared: harness_dataguard::plugins::Shared,
) -> Result<Engine, PlantError> {
    let mut engine = engine.with_registry(Registry::parse(registry::REGISTRY)?);
    for text in registry::AGGREGATES {
        engine = engine.with_aggregate(Aggregate::parse(text)?);
    }
    for text in registry::DATA_CAPABILITIES {
        engine = engine.with_data_capability(DataCapability::parse(text)?);
    }
    // engine = engine.with_proposer(Arc::new(my_product::Proposer));
    Ok(engine.with_plugins(plugins).with_shared(shared))
}

/// The shell's wire protocol, answered by `engine`, whose rows are `rows`;
/// `llm` is the port an analysis of notes reaches (a generic: [`Llm`] is
/// not dyn-compatible). No Capability reads a row, and the `speech-to-text`
/// port's fake hears nothing in a dictation: see [`router_reading`].
pub fn router<L: Llm + 'static>(engine: Arc<Engine>, rows: Rows, llm: Arc<L>) -> Router {
    router_reading(
        engine,
        rows,
        llm,
        Arc::new(FakeSpeechToText::new(String::new())),
        Arc::new(Reads::none()),
    )
}

/// [`router`], a dictation transcribed by `speech` and its reads answered
/// through `reads`.
pub fn router_reading<L: Llm + 'static, S: SpeechToText + 'static>(
    engine: Arc<Engine>,
    rows: Rows,
    llm: Arc<L>,
    speech: Arc<S>,
    reads: Arc<Reads>,
) -> Router {
    Router::new()
        .route("/capabilities/{id}", post(capability))
        .route("/commands", post(submit::<L, S>))
        .route("/commands/{id}", get(status))
        .route("/commands/{id}/confirm", post(confirm))
        .route("/commands/{id}/cancel", post(cancel))
        .route("/commands/{id}/requeue", post(requeue))
        .route("/holds", post(hold))
        .route("/holds/{id}/renew", post(renew))
        .route("/holds/{id}/release", post(release))
        .route("/reviews/{id}", post(decide))
        .route("/dataVersion", get(version))
        .with_state(Served {
            engine,
            rows,
            llm,
            speech,
            reads,
            exports: Arc::default(),
        })
}

/// The single applier: every second, each partition's head. It runs until
/// the handle is aborted.
pub fn applier(engine: Arc<Engine>) -> tokio::task::JoinHandle<()> {
    tokio::spawn(async move {
        loop {
            tokio::time::sleep(std::time::Duration::from_secs(1)).await;
            if let Err(e) = engine.run_once().await {
                eprintln!("applier: {e}");
            }
        }
    })
}

fn status_of(error: &Error) -> axum::http::StatusCode {
    use axum::http::StatusCode;
    match error {
        Error::NotFound(_) | Error::UnknownDataCapability(_) | Error::UnregisteredQuery(_) => {
            StatusCode::NOT_FOUND
        }
        Error::Forbidden(_) => StatusCode::FORBIDDEN,
        Error::NotNow(_) => StatusCode::CONFLICT,
        Error::Store(_) => StatusCode::SERVICE_UNAVAILABLE,
        Error::Misconfigured(_) => StatusCode::INTERNAL_SERVER_ERROR,
        Error::Refused(refusal) => match refusal.kind {
            RefusalKind::NotFound => StatusCode::NOT_FOUND,
            RefusalKind::Unprocessable => StatusCode::UNPROCESSABLE_ENTITY,
        },
    }
}

type Reply<T> =
    Result<(axum::http::StatusCode, Json<T>), (axum::http::StatusCode, Json<serde_json::Value>)>;

fn reply<T>(status: axum::http::StatusCode, result: Result<T, Error>) -> Reply<T> {
    result.map(|value| (status, Json(value))).map_err(|e| {
        (
            status_of(&e),
            Json(serde_json::json!({ "error": e.to_string() })),
        )
    })
}

/// A command enters the queue. A DataCapability the legacy chain still
/// prepares is first made what it writes by its own module of [`legacy`] —
/// its arm below, deleted with the module once its `Prepare` moves to its
/// crate; any other is the engine's alone, its `Prepare` included.
///
/// The element a command targets is its `targetId`, or the `id` of its
/// `target`, as the Micro-UIs and the rules' tests name it.
async fn submit<L: Llm, S: SpeechToText>(
    State(served): State<Served<L, S>>,
    Json(raw): Json<serde_json::Value>,
) -> Reply<harness_dataguard::api::Submitted> {
    let body: Submission = match serde_json::from_value(raw) {
        Ok(body) => body,
        Err(e) => {
            return Err((
                axum::http::StatusCode::UNPROCESSABLE_ENTITY,
                Json(serde_json::json!({ "error": e.to_string() })),
            ));
        }
    };
    let now = now();
    let served = &served;
    match body.data_capability.split('@').next().unwrap_or_default() {
        // ---
        extract_from_notes::DATA_CAPABILITY => {
            legacy::extract_from_notes::submit(served, body, &now).await
        }
        // ---
        create_entities_from_note::DATA_CAPABILITY => {
            legacy::create_entities_from_note::submit(served, body, &now).await
        }
        // ---
        save_entity::DATA_CAPABILITY => legacy::save_entity::submit(served, body, &now).await,
        // ---
        restore_entity_version::DATA_CAPABILITY => {
            legacy::restore_entity_version::submit(served, body, &now).await
        }
        // ---
        export_campaign::DATA_CAPABILITY => {
            legacy::export_campaign::submit(served, body, &now).await
        }
        // ---
        _ => reply(
            axum::http::StatusCode::ACCEPTED,
            served.engine.submit(body).await,
        ),
    }
}

/// Now, to the millisecond (RFC 3339), as the AiSettings aggregate stamps
/// it (`aggregate_ai_settings::timestamp`).
fn now() -> String {
    let elapsed = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default();
    aggregate_ai_settings::timestamp(u64::try_from(elapsed.as_millis()).unwrap_or(u64::MAX))
}

/// `body` queued by the engine, as the legacy chain leaves it: `warning`
/// told after the engine's own, `archive` kept until the command is applied
/// ([`status`]).
async fn queued<L, S>(
    served: &Served<L, S>,
    body: Submission,
    warning: Option<&str>,
    archive: Option<export_campaign::Archive>,
) -> Reply<harness_dataguard::api::Submitted> {
    let submitted = submit_prepared(served, body).await.map(|mut submitted| {
        submitted.warnings.extend(warning.map(str::to_string));
        if let Some(archive) = archive {
            served.exports.keep(&submitted.command_id, archive);
        }
        submitted
    });
    reply(axum::http::StatusCode::ACCEPTED, submitted)
}

/// What the engine answers to `body`, which the legacy chain prepared: its
/// payload is the fields the command writes, never the wire's, so the
/// engine's check of the wire's keys — `payload key(s) … not declared by
/// <id>` — says nothing of it and is left out.
async fn submit_prepared<L, S>(
    served: &Served<L, S>,
    body: Submission,
) -> Result<harness_dataguard::api::Submitted, Error> {
    let undeclared = format!(
        " not declared by {}",
        body.data_capability.split('@').next().unwrap_or_default()
    );
    served.engine.submit(body).await.map(|mut submitted| {
        submitted.warnings.retain(|warning| {
            warning
                .strip_prefix("payload key(s) ")
                .is_none_or(|keys| !keys.ends_with(&undeclared))
        });
        submitted
    })
}

/// A random (version 4) uuid: a new element's id, a version's.
fn fresh_uuid() -> Result<String, getrandom::Error> {
    let mut bytes = [0_u8; 16];
    getrandom::fill(&mut bytes)?;
    // The version (4) and the variant (10), on the bits cleared for them.
    bytes[6] = 0x40 + (bytes[6] & 0x0f);
    bytes[8] = 0x80 + (bytes[8] & 0x3f);
    let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    Ok(format!(
        "{}-{}-{}-{}-{}",
        &hex[..8],
        &hex[8..12],
        &hex[12..16],
        &hex[16..20],
        &hex[20..]
    ))
}

/// A command's result; an export's, once applied, with its archive —
/// `result.archive.file`, the file's name, and `result.archive.content`, the
/// document —
/// which the shell hands to the DM as a download.
async fn status(
    State(engine): State<Shared>,
    State(exports): State<Arc<exports::Exports>>,
    Path(id): Path<String>,
) -> Reply<serde_json::Value> {
    reply(
        axum::http::StatusCode::OK,
        engine.status(&id).await.map(|r| {
            let mut answer = serde_json::json!({ "result": r });
            let applied = answer["result"]["status"] == "applied";
            if let Some(archive) = exports.of(&id).filter(|_| applied) {
                answer["result"]["archive"] =
                    serde_json::json!({ "file": archive.file, "content": archive.content });
            }
            answer
        }),
    )
}

